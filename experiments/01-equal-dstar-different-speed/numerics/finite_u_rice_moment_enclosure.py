#!/usr/bin/env python3
"""Step-32 finite-u Rice moment enclosure.

For a smooth finite-band stationary Gaussian timing scan z(t), define

    X_u = 1{z(0) <= u} N_u^+

where N_u^+ is the number of upcrossings of level u on [0,ell].  Then

    P_FA = Q(u) + P(X_u >= 1)

and

    Q(u) + E[X_u]^2 / E[(N_u^+)^2]
        <= P_FA <=
    Q(u) + E[X_u].

This script evaluates the required first- and second-order Rice moments from
R(t), R'(t), and R''(t) generated by the controlled finite-band spectrum

    |H_x(omega)|^2 exp[-(omega/kappa)^2].

The inequalities are analytic.  The implementation uses deterministic FFT,
Gauss-Hermite, and trapezoidal quadrature; it is not formal interval arithmetic.
"""

from __future__ import annotations

import argparse
import math

import numpy as np
from numpy.polynomial.hermite import hermgauss
from scipy.special import ndtr
from scipy.stats import norm


RHO_FULL = 6.2407571
BETA = 0.90
ALPHA = 1.0e-6


def H_x(omega: np.ndarray, x: float) -> np.ndarray:
    z = 1.0 + 1j * omega
    return (1.0 - np.exp(-z * x) * (1.0 + z * x)) / (z * z)


def finite_rho(x: float, kappa: float, d_omega: float = 0.03) -> float:
    upper = max(30.0, 6.0 * kappa)
    n = int(math.ceil(upper / d_omega)) + 1
    omega = np.linspace(0.0, upper, n)
    density = np.abs(H_x(omega, x)) ** 2 * np.exp(-(omega / kappa) ** 2)
    i0 = 2.0 * float(np.trapezoid(density, omega))
    return RHO_FULL * math.sqrt(i0 / (math.pi / 2.0))


def covariance_grid(
    x: float,
    kappa: float,
    delta: float,
    period_target: float = 16.0,
) -> tuple[np.ndarray, np.ndarray, np.ndarray, float, float]:
    nfft = 1
    while nfft * delta < period_target:
        nfft *= 2

    omega = 2.0 * math.pi * np.fft.fftfreq(nfft, d=delta)
    eig = np.abs(H_x(omega, x)) ** 2 * np.exp(-(omega / kappa) ** 2)

    c0 = float(np.fft.ifft(eig).real[0])
    r = np.fft.ifft(eig).real / c0
    rp = np.fft.ifft(1j * omega * eig).real / c0
    rpp = np.fft.ifft(-(omega**2) * eig).real / c0
    sigma2 = -float(rpp[0])
    return r, rp, rpp, sigma2, nfft * delta


GH_NODES, GH_WEIGHTS = hermgauss(48)
GH_Z = math.sqrt(2.0) * GH_NODES
GH_W = GH_WEIGHTS / math.sqrt(math.pi)


def positive_product_bivariate(
    mean1: np.ndarray,
    mean2: np.ndarray,
    variance: np.ndarray,
    covariance: np.ndarray,
) -> np.ndarray:
    """E[Y1_+ Y2_+] for equal-variance bivariate Gaussians, vectorized."""
    variance = np.maximum(np.asarray(variance), 1.0e-14)
    sd = np.sqrt(variance)
    rho = np.clip(np.asarray(covariance) / variance, -0.999999999, 0.999999999)
    cond_sd = sd * np.sqrt(np.maximum(1.0 - rho * rho, 1.0e-16))

    z = GH_Z[None, :]
    y1 = mean1[:, None] + sd[:, None] * z
    cond_mean2 = mean2[:, None] + rho[:, None] * sd[:, None] * z
    a = cond_mean2 / cond_sd[:, None]
    e_y2_pos = (
        cond_sd[:, None] * np.exp(-0.5 * a * a) / math.sqrt(2.0 * math.pi)
        + cond_mean2 * ndtr(a)
    )
    return (np.maximum(y1, 0.0) * e_y2_pos) @ GH_W


def moment_enclosure(
    *,
    x: float,
    ell: float,
    kappa: float,
    u: float,
    resolution_scale: float = 0.02,
    period_target: float = 16.0,
) -> dict[str, float]:
    delta = min(5.0e-4, resolution_scale / kappa)
    r_all, rp_all, rpp_all, sigma2, period = covariance_grid(
        x=x,
        kappa=kappa,
        delta=delta,
        period_target=period_target,
    )
    sigma = math.sqrt(sigma2)

    n = max(2, int(round(ell / delta)))
    h = np.arange(1, n + 1, dtype=float) * delta
    r = r_all[1 : n + 1]
    rp = rp_all[1 : n + 1]
    rpp = rpp_all[1 : n + 1]

    q_tail = float(norm.sf(u))
    phi_u = math.exp(-0.5 * u * u) / math.sqrt(2.0 * math.pi)

    # E[N_u^+]
    lam = ell * sigma / (2.0 * math.pi) * math.exp(-0.5 * u * u)

    # J0 = E[N_u^+ 1{z(0)>u}].
    # Condition on z(h)=u and integrate z'(h)_+ P[z(0)>u | z'(h),z(h)=u].
    sy2 = np.maximum(1.0 - r * r, 1.0e-300)
    cov_y_d = rp
    cond_y2 = np.maximum(sy2 - cov_y_d * cov_y_d / sigma2, 1.0e-300)
    cond_y_sd = np.sqrt(cond_y2)

    z = GH_Z[None, :]
    deriv = sigma * z
    mean_y = r[:, None] * u + (cov_y_d / sigma)[:, None] * z
    p_y_above = ndtr((mean_y - u) / cond_y_sd[:, None])
    e_deriv_pos_and_y = (np.maximum(deriv, 0.0) * p_y_above) @ GH_W
    overlap_density = phi_u * e_deriv_pos_and_y
    overlap = float(
        np.trapezoid(
            np.concatenate(([0.0], overlap_density)),
            np.concatenate(([0.0], h)),
        )
    )

    m1 = max(lam - overlap, 0.0)

    # Second factorial moment E[N(N-1)].
    denom = np.maximum(1.0 - r * r, 1.0e-300)
    mean_left = -rp * u / (1.0 + r)
    mean_right = rp * u / (1.0 + r)
    cond_var = sigma2 - rp * rp / denom
    cond_cov = -rpp - r * rp * rp / denom

    e_pos_prod = positive_product_bivariate(
        mean_left,
        mean_right,
        cond_var,
        cond_cov,
    )

    value_density = (
        np.exp(-(u * u) / (1.0 + r))
        / (2.0 * math.pi * np.sqrt(denom))
    )
    rho2 = value_density * e_pos_prod
    lambda2 = 2.0 * float(np.trapezoid((ell - h) * rho2, h))

    e_n2 = lam + lambda2
    extra_lower = m1 * m1 / e_n2 if e_n2 > 0.0 else 0.0
    extra_upper = m1

    return {
        "u": u,
        "Q": q_tail,
        "lambda": lam,
        "endpoint_overlap": overlap,
        "m1_start_below": m1,
        "lambda2": lambda2,
        "EN2": e_n2,
        "PFA_lower": q_tail + extra_lower,
        "PFA_upper": q_tail + extra_upper,
        "delta": delta,
        "period": period,
        "sigma": sigma,
    }


def detector_bounds(
    *,
    kappa_fast: float,
    X: float,
    Lambda: float,
    resolution_scale: float,
) -> tuple[dict[str, float], dict[str, float]]:
    r_speed = 2.0
    z_beta = float(norm.ppf(BETA))

    x_f = X
    x_s = X / r_speed
    ell_f = Lambda
    ell_s = Lambda / r_speed
    k_f = kappa_fast
    k_s = r_speed * kappa_fast

    u_f = finite_rho(x_f, k_f) - z_beta
    u_s = finite_rho(x_s, k_s) - z_beta

    fast = moment_enclosure(
        x=x_f,
        ell=ell_f,
        kappa=k_f,
        u=u_f,
        resolution_scale=resolution_scale,
    )
    slow = moment_enclosure(
        x=x_s,
        ell=ell_s,
        kappa=k_s,
        u=u_s,
        resolution_scale=resolution_scale,
    )
    return fast, slow


def main() -> None:
    p = argparse.ArgumentParser()
    p.add_argument("--kappas", default="100,130,160,170,175,200")
    p.add_argument("--X", type=float, default=7.04)
    p.add_argument("--Lambda", type=float, default=0.895)
    p.add_argument("--resolution-scale", type=float, default=0.02)
    p.add_argument(
        "--refine-kappa",
        type=float,
        default=160.0,
        help="also print the standard Step-32 resolution refinement at this kappa",
    )
    args = p.parse_args()

    kappas = [float(v) for v in args.kappas.split(",") if v.strip()]

    print("Finite-u second-moment Rice enclosure")
    print(f"X={args.X}, Lambda={args.Lambda}, alpha={ALPHA}")
    print("kappa_f   fast_upper/alpha   slow_lower/alpha   separated")
    for kappa in kappas:
        fast, slow = detector_bounds(
            kappa_fast=kappa,
            X=args.X,
            Lambda=args.Lambda,
            resolution_scale=args.resolution_scale,
        )
        fu = fast["PFA_upper"] / ALPHA
        sl = slow["PFA_lower"] / ALPHA
        print(f"{kappa:7.1f}   {fu:16.8f}   {sl:16.8f}   {fu < 1.0 < sl}")

    print(f"\nResolution refinement at kappa_f={args.refine_kappa:g}")
    print("scale      fast_upper/alpha   slow_lower/alpha   slow_lambda2")
    for scale in [0.040, 0.030, 0.020, 0.015]:
        fast, slow = detector_bounds(
            kappa_fast=args.refine_kappa,
            X=args.X,
            Lambda=args.Lambda,
            resolution_scale=scale,
        )
        print(
            f"{scale:5.3f}      {fast['PFA_upper']/ALPHA:14.8f}   "
            f"{slow['PFA_lower']/ALPHA:14.8f}   {slow['lambda2']:.8e}"
        )

    print(
        "\nInterpretation: if fast_upper/alpha < 1 < slow_lower/alpha at the same X, "
        "the fast detector is guaranteed feasible while the slow detector is still "
        "infeasible under the analytic moment enclosure."
    )
    print(
        "NOTE: the inequalities are analytic; the reported numbers use deterministic "
        "floating-point quadrature, not formal interval arithmetic."
    )


if __name__ == "__main__":
    main()
