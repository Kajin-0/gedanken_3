#!/usr/bin/env python3
"""Step 49 exact finite-window covariance grid-transfer calculator.

This helper simulates the exact finite-window scan covariance for
h_x(v)=v exp(-v) 1_[0,x](v) using the exact two-state filter representation

    Z_raw(t)=V(t)-exp(-x)[V(t-x)+x U(t-x)]

where

    dU=-U dt+dW,
    dV=(U-V)dt.

The state transition over each step is exact. The script evaluates the
finite-u Brown-Resnick spectral process generated by the exact covariance on
a coarse physical timing lattice dt=.001 and a nested 32x finer lattice.
It reports the paired generalized discrete Dieker-Yakir relative loss.

This is a Monte Carlo diagnostic of the exact-covariance spectral intensity,
not an exact finite-u false-alarm probability or a distribution-free CI.
"""

from __future__ import annotations

import argparse
import math
import numpy as np
from scipy.linalg import expm

try:
    from numba import njit
except ImportError:  # pragma: no cover
    njit = lambda f: f

X_DEFAULT = 7.16
U_DEFAULT = 4.9589834838
B_DEFAULT = 1.0001238283
DT_DEFAULT = 0.001
REFINE_DEFAULT = 32
T_DEFAULT = 4.0

A_STATE = np.array([[-1.0, 0.0], [1.0, -1.0]])
P_STATE = np.array([[0.5, 0.25], [0.25, 0.25]])


def eta(x: float) -> float:
    return 1.0 - math.exp(-2.0*x)*(1.0 + 2.0*x + 2.0*x*x)


def i1(A: np.ndarray | float):
    return (1.0 - (1.0 + 2.0*A)*np.exp(-2.0*A))/4.0


def i2(A: np.ndarray | float):
    return (1.0 - (1.0 + 2.0*A + 2.0*A*A)*np.exp(-2.0*A))/4.0


def R_exact(y: np.ndarray, x: float) -> np.ndarray:
    y = np.abs(np.asarray(y, dtype=float))
    A = x-y
    D = float(i2(x))
    out = np.zeros_like(y)
    mask = y < x
    Am = A[mask]
    ym = y[mask]
    out[mask] = np.exp(-ym)*(i2(Am)+ym*i1(Am))/D
    return out


def transition(dt: float):
    Phi = expm(A_STATE*dt)
    Q = P_STATE-Phi@P_STATE@Phi.T
    Q = 0.5*(Q+Q.T)
    # Tiny diagonal regularizer only protects Cholesky against roundoff for
    # extremely small dt. It is many orders below the physical innovation.
    L = np.linalg.cholesky(Q+1e-20*np.eye(2))
    return Phi, L


@njit
def _simulate(
    npaths, seed, n_half, refine, u_thr, x, sqrtD,
    Phi_f, L_f, Phi_g, L_g, L_P, garr, dt_tan
):
    np.random.seed(seed)
    nwin = 2*n_half+1
    coarse = np.empty(npaths)
    fine = np.empty(npaths)
    ud = np.empty(nwin)
    vd = np.empty(nwin)
    zvals = np.empty(nwin)
    ex = math.exp(-x)

    for p in range(npaths):
        r1 = np.random.randn(); r2 = np.random.randn()
        U = L_P[0,0]*r1
        V = L_P[1,0]*r1 + L_P[1,1]*r2
        ud[0] = U; vd[0] = V

        # Delayed window.
        for i in range(1, nwin):
            r1 = np.random.randn(); r2 = np.random.randn()
            Un = Phi_f[0,0]*U + Phi_f[0,1]*V + L_f[0,0]*r1 + L_f[0,1]*r2
            Vn = Phi_f[1,0]*U + Phi_f[1,1]*V + L_f[1,0]*r1 + L_f[1,1]*r2
            U, V = Un, Vn
            ud[i] = U; vd[i] = V

        # Exact Markov jump from end of delayed window to start of current window.
        r1 = np.random.randn(); r2 = np.random.randn()
        Un = Phi_g[0,0]*U + Phi_g[0,1]*V + L_g[0,0]*r1 + L_g[0,1]*r2
        Vn = Phi_g[1,0]*U + Phi_g[1,1]*V + L_g[1,0]*r1 + L_g[1,1]*r2
        U, V = Un, Vn

        zvals[0] = (V-ex*(vd[0]+x*ud[0]))/sqrtD
        for i in range(1, nwin):
            r1 = np.random.randn(); r2 = np.random.randn()
            Un = Phi_f[0,0]*U + Phi_f[0,1]*V + L_f[0,0]*r1 + L_f[0,1]*r2
            Vn = Phi_f[1,0]*U + Phi_f[1,1]*V + L_f[1,0]*r1 + L_f[1,1]*r2
            U, V = Un, Vn
            zvals[i] = (V-ex*(vd[i]+x*ud[i]))/sqrtD

        z0 = zvals[n_half]

        maxf = -1e300
        for i in range(nwin):
            W = u_thr*(zvals[i]-z0)-garr[i]
            if W > maxf:
                maxf = W
        sumf = 0.0
        for i in range(nwin):
            W = u_thr*(zvals[i]-z0)-garr[i]
            sumf += math.exp(W-maxf)
        fine[p] = 1.0/(dt_tan*sumf)

        kmax = n_half//refine
        maxc = -1e300
        for k in range(-kmax, kmax+1):
            i = n_half+k*refine
            W = u_thr*(zvals[i]-z0)-garr[i]
            if W > maxc:
                maxc = W
        sumc = 0.0
        for k in range(-kmax, kmax+1):
            i = n_half+k*refine
            W = u_thr*(zvals[i]-z0)-garr[i]
            sumc += math.exp(W-maxc)
        coarse[p] = 1.0/((dt_tan*refine)*sumc)

    return coarse, fine


def run(paths: int, seed: int, x: float, u_thr: float, b: float,
        dt: float, refine: int, T: float):
    dt_fine = dt/refine
    Delta = u_thr*math.sqrt(b)/math.sqrt(2.0)*dt
    dt_tan = Delta/refine
    n_half = int(round(T/dt_tan))
    physical_half = n_half*dt_fine
    gap = x-2.0*physical_half
    if gap <= 0:
        raise ValueError("T is too large for the two-window delayed-state construction")

    Phi_f, L_f = transition(dt_fine)
    Phi_g, L_g = transition(gap)
    L_P = np.linalg.cholesky(P_STATE)
    sqrtD = math.sqrt(eta(x)/4.0)

    physical = np.arange(-n_half, n_half+1)*dt_fine
    tangent = np.arange(-n_half, n_half+1)*dt_tan
    garr = u_thr*u_thr*(1.0-R_exact(physical, x))

    coarse, fine = _simulate(
        paths, seed, n_half, refine, u_thr, x, sqrtD,
        Phi_f, L_f, Phi_g, L_g, L_P, garr, dt_tan
    )

    mc = float(coarse.mean())
    mf = float(fine.mean())
    ratio = mc/mf
    loss = 1.0-ratio
    influence = (coarse-ratio*fine)/mf
    se = float(influence.std(ddof=1)/math.sqrt(paths))

    return {
        "paths": paths,
        "seed": seed,
        "H_exact_coarse": mc,
        "H_exact_fine": mf,
        "relative_loss": loss,
        "paired_SE": se,
        "normal_95_low": loss-1.96*se,
        "normal_95_high": loss+1.96*se,
        "actual_T": n_half*dt_tan,
        "physical_half_window": physical_half,
        "gap": gap,
        "coarse_Delta": Delta,
        "fine_Delta": dt_tan,
        "cell_exact_g": float(garr[n_half+refine]),
    }


def pool(rows):
    # For reproducibility this rerun helper prints individual rows. The pooled
    # values in Step 49 were obtained by concatenating the paired samples from
    # the two default seeds before applying the same ratio/delta-method formula.
    return rows


def main():
    p = argparse.ArgumentParser()
    p.add_argument("--paths", type=int, default=3000)
    p.add_argument("--seeds", default="20260820,20260821")
    p.add_argument("--X", type=float, default=X_DEFAULT)
    p.add_argument("--u", type=float, default=U_DEFAULT)
    p.add_argument("--b", type=float, default=B_DEFAULT)
    p.add_argument("--dt", type=float, default=DT_DEFAULT)
    p.add_argument("--refine", type=int, default=REFINE_DEFAULT)
    p.add_argument("--T", type=float, default=T_DEFAULT)
    args = p.parse_args()

    rows = []
    for s in [int(v) for v in args.seeds.split(",") if v.strip()]:
        r = run(args.paths, s, args.X, args.u, args.b,
                args.dt, args.refine, args.T)
        rows.append(r)
        print("\nseed", s)
        for k,v in r.items():
            print(f"{k}: {v}")

    print("\nNOTE: Step 49 pooled the raw paired samples from both seeds; do not average the two reported ratios as a substitute for raw-sample pooling.")
    print("This calculator evaluates the exact-covariance spectral-intensity grid transfer only; it is not an exact finite-u false-alarm probability.")


if __name__ == "__main__":
    main()
