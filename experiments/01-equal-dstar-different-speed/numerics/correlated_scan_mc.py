"""Correlated finite-duration Gaussian timing-scan Monte Carlo prototype.

Experiment 01 / Step 13.

This intentionally simulates the correlated moving-average scan generated by the
finite matched-filter template. It does NOT replace the scan by an effective
number of independent trials.

Important: the maximum is evaluated only on a timing grid. Step 13 shows that
the finite hard-window process has a covariance cusp and is locally rough, so
grid maxima converge slowly to the continuous supremum. Use this script for
convergence studies, not as an exact continuous-time threshold calculator.
"""

from __future__ import annotations

import numpy as np
from scipy.signal import fftconvolve


def eta(x: float) -> float:
    """Squared-SNR accumulation fraction for h(v)=v exp(-v), 0<=v<=x."""
    return float(1.0 - np.exp(-2.0 * x) * (1.0 + 2.0 * x + 2.0 * x * x))


def cusp_coefficient(x: float) -> float:
    """a_x in R_x(y)=1-a_x |y|+O(y^2) for the hard-window scan."""
    return float(2.0 * x * x * np.exp(-2.0 * x) / eta(x))


def midpoint_template(x: float, delta: float) -> np.ndarray:
    """Normalized midpoint discretization of h_x(v)=v exp(-v) 1_[0,x]."""
    n = max(1, int(round(x / delta)))
    v = (np.arange(n, dtype=float) + 0.5) * delta
    h = v * np.exp(-v)
    return h / np.linalg.norm(h)


def scan_maxima(
    x: float,
    ell_values: np.ndarray,
    *,
    delta: float,
    n_paths: int,
    batch: int = 500,
    seed: int = 12345,
) -> np.ndarray:
    """Simulate grid-sampled correlated scan maxima for several search lengths.

    Returns an array with shape (n_paths, len(ell_values)). ell_values must be
    nonnegative and are interpreted in units of detector time scale tau.
    """
    ell_values = np.asarray(ell_values, dtype=float)
    if np.any(ell_values < 0):
        raise ValueError("ell_values must be nonnegative")
    order = np.argsort(ell_values)
    sorted_ell = ell_values[order]

    h = midpoint_template(x, delta)
    n_h = h.size
    max_ell = float(sorted_ell[-1])
    n_scan = int(round(max_ell / delta)) + 1
    indices = np.array([int(round(e / delta)) for e in sorted_ell], dtype=int)

    rng = np.random.default_rng(seed)
    out_sorted = np.empty((n_paths, len(sorted_ell)), dtype=np.float32)

    done = 0
    while done < n_paths:
        b = min(batch, n_paths - done)
        white = rng.standard_normal((b, n_scan + n_h - 1))
        z = fftconvolve(white, h[None, :], mode="valid", axes=1)

        running = np.full(b, -np.inf)
        start = 0
        for j, idx in enumerate(indices):
            running = np.maximum(running, z[:, start : idx + 1].max(axis=1))
            out_sorted[done : done + b, j] = running
            start = idx + 1
        done += b

    inverse = np.argsort(order)
    return out_sorted[:, inverse]


def gamma_grid(
    x: float,
    ell_values: np.ndarray,
    *,
    alpha: float,
    delta: float,
    n_paths: int,
    batch: int = 500,
    seed: int = 12345,
) -> np.ndarray:
    """Empirical (1-alpha) quantile of grid-sampled scan maxima."""
    maxima = scan_maxima(
        x,
        ell_values,
        delta=delta,
        n_paths=n_paths,
        batch=batch,
        seed=seed,
    )
    return np.quantile(maxima, 1.0 - alpha, axis=0)


if __name__ == "__main__":
    # Small smoke/convergence example only.
    x = 4.0
    ell = np.array([10.0, 20.0, 40.0])
    for delta in (0.1, 0.05, 0.025):
        q = gamma_grid(
            x,
            ell,
            alpha=0.01,
            delta=delta,
            n_paths=5000,
            seed=20260811,
        )
        print(f"delta={delta:7.4f}  gamma={q}")
    print(f"a_x={cusp_coefficient(x):.8g}")
